import "server-only";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

/** ECHOES_SECRET: 32+ random bytes (hex). Generated into .env.local on first use if missing. */
let cached: Buffer | null = null;
export function masterSecret(): Buffer {
  if (cached) return cached;
  let s = process.env.ECHOES_SECRET;
  if (!s) {
    const file = path.join(process.cwd(), ".env.local");
    const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    const m = existing.match(/^ECHOES_SECRET=(.+)$/m);
    if (m) s = m[1].trim();
    else {
      s = crypto.randomBytes(32).toString("hex");
      fs.writeFileSync(file, `${existing}${existing && !existing.endsWith("\n") ? "\n" : ""}# Generated by Echoes. Encrypts stored AI keys — keep it secret; changing it makes stored keys unreadable.\nECHOES_SECRET=${s}\n`, { mode: 0o600 });
      console.warn("[echoes] ECHOES_SECRET was missing — generated one into .env.local");
    }
    process.env.ECHOES_SECRET = s;
  }
  if (s.length < 32) throw new Error("ECHOES_SECRET must be at least 32 characters");
  cached = Buffer.from(s, "utf8");
  return cached;
}
function derive(label: string) {
  return Buffer.from(crypto.hkdfSync("sha256", masterSecret(), Buffer.from("echoes-v1"), Buffer.from(label), 32));
}

export type Sealed = { iv: string; tag: string; ct: string };
/** AES-256-GCM with a key derived (HKDF-SHA256) from ECHOES_SECRET; the user id is bound as AAD. */
export function seal(plain: string, aad: string): Sealed {
  const iv = crypto.randomBytes(12);
  const c = crypto.createCipheriv("aes-256-gcm", derive("ai-key"), iv);
  c.setAAD(Buffer.from(aad));
  const ct = Buffer.concat([c.update(plain, "utf8"), c.final()]);
  return { iv: iv.toString("base64"), tag: c.getAuthTag().toString("base64"), ct: ct.toString("base64") };
}
export function open(s: Sealed, aad: string): string {
  const d = crypto.createDecipheriv("aes-256-gcm", derive("ai-key"), Buffer.from(s.iv, "base64"));
  d.setAAD(Buffer.from(aad));
  d.setAuthTag(Buffer.from(s.tag, "base64"));
  return Buffer.concat([d.update(Buffer.from(s.ct, "base64")), d.final()]).toString("utf8");
}
